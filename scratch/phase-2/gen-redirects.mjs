#!/usr/bin/env node
/**
 * gen-redirects.mjs — Emit Cloudflare Pages `public/_redirects` from legacy paths.
 *
 * Source-of-truth for legacy paths: the `legacyPath` field on JSON entries under
 *   - src/content/journal-issues/*.json   (issue index pages)
 *   - src/content/journal/*.json          (journal articles)
 *   - src/content/conferences/*.json      (conference listings; reviews skipped)
 *
 * Mapping rules:
 *   - Journal article (entry has `issueNumber`):  /journal/issue/issue-NN/<slug>/
 *   - Journal issue JSON:                        /journal/issue/issue-NN/
 *   - Conference with `year` (section=conference): /conferences/<year>/
 *   - Conference review (primaryCategory=review, year=0): skip (Phase 2b)
 *   - Anything else with a legacyPath: skip (no canonical route yet)
 *
 * Output: Cloudflare Pages _redirects lines:
 *   <source> <target> 301
 * Comments starting with `#` are preserved. Empty lines are stripped.
 */

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, resolve } from 'node:path';

const PROJECT_ROOT = resolve(process.cwd());
const SRC = join(PROJECT_ROOT, 'src', 'content');
const OUT = join(PROJECT_ROOT, 'public', '_redirects');

const pad2 = (n) => String(n).padStart(2, '0');

function readJson(p) {
  return JSON.parse(readFileSync(p, 'utf8'));
}

function listJson(dir) {
  try {
    return readdirSync(dir)
      .filter((f) => f.endsWith('.json'))
      .map((f) => join(dir, f));
  } catch {
    return [];
  }
}

/**
 * Derive the canonical target URL for a content entry.
 * Returns null when the entry has no mappable legacy route.
 */
function targetFor(entry, sourceKind) {
  const legacy = entry.legacyPath;
  if (!legacy || typeof legacy !== 'string') return null;

  if (sourceKind === 'journal-article') {
    const n = entry.issueNumber;
    if (typeof n !== 'number') return null;
    const issueSeg = `issue-${pad2(n)}`;
    // slug = filename stem. Astro loader sets id from the file path (no `.json`),
    // but we read directly so derive it ourselves.
    // The slug used in `/journal/issue/issue-NN/<slug>/` is the file stem
    // minus the `.json` extension. Keep that exact mapping here so it matches
    // `src/pages/journal/issue/[issue]/[slug].astro`.
    return null; // populated by caller (needs the file stem)
  }

  if (sourceKind === 'journal-issue') {
    const n = entry.issueNumber;
    if (typeof n !== 'number') return null;
    return `/journal/issue/issue-${pad2(n)}/`;
  }

  if (sourceKind === 'conference') {
    // Reviews: primaryCategory === 'review' and no real year -> skip.
    if (entry.primaryCategory === 'review' && (!entry.year || entry.year === 0)) {
      return null;
    }
    if (entry.section !== 'conference') return null;
    if (typeof entry.year !== 'number' || entry.year === 0) return null;
    return `/conferences/${entry.year}/`;
  }

  return null;
}

/** Normalise a legacy path for the redirect source. */
function normaliseSource(p) {
  if (!p.startsWith('/')) return '/' + p;
  return p.endsWith('/') ? p : p + '/';
}

const redirects = []; // { source, target }
const orphans = []; // { file, reason, legacy }

function record(file, entry, sourceKind) {
  const legacy = entry.legacyPath;
  if (!legacy || typeof legacy !== 'string') {
    orphans.push({ file, reason: 'no legacyPath', legacy });
    return;
  }

  let target = null;

  if (sourceKind === 'journal-article') {
    const n = entry.issueNumber;
    if (typeof n !== 'number') {
      orphans.push({ file, reason: 'journal-article without issueNumber', legacy });
      return;
    }
    // slug = filename stem
    const stem = file.replace(/\.json$/, '').split('/').pop();
    target = `/journal/issue/issue-${pad2(n)}/${stem}/`;
  } else if (sourceKind === 'journal-issue') {
    target = targetFor(entry, 'journal-issue');
  } else if (sourceKind === 'conference') {
    target = targetFor(entry, 'conference');
  }

  if (!target) {
    orphans.push({ file, reason: 'no canonical route', legacy });
    return;
  }

  const source = normaliseSource(legacy);
  redirects.push({ source, target });
}

// Journal issues
for (const f of listJson(join(SRC, 'journal-issues'))) {
  const entry = readJson(f);
  record(f, entry, 'journal-issue');
}

// Journal articles
for (const f of listJson(join(SRC, 'journal'))) {
  const entry = readJson(f);
  record(f, entry, 'journal-article');
}

// Conferences
for (const f of listJson(join(SRC, 'conferences'))) {
  const entry = readJson(f);
  record(f, entry, 'conference');
}

// Dedupe by source (last write wins, but they should agree)
const bySource = new Map();
for (const r of redirects) bySource.set(r.source, r.target);
const finalRows = [...bySource.entries()]
  .map(([source, target]) => ({ source, target }))
  .sort((a, b) => (a.source < b.source ? -1 : a.source > b.source ? 1 : 0));

// Build file
const header = [
  '# Cloudflare Pages redirects for BRF2.',
  '# Generated by scratch/phase-2/gen-redirects.mjs — do not hand-edit.',
  `# Total redirects: ${finalRows.length}`,
  '',
];

const body = finalRows.map((r) => `${r.source} ${r.target} 301`).join('\n');

const out = header.join('\n') + body + '\n';

writeFileSync(OUT, out, 'utf8');

const bytes = Buffer.byteLength(out, 'utf8');
console.log(`Wrote ${OUT}`);
console.log(`Redirects: ${finalRows.length}`);
console.log(`Bytes:     ${bytes}`);
console.log(`Orphans:   ${orphans.length}`);
if (orphans.length > 0) {
  console.log('--- Orphan breakdown ---');
  const byReason = new Map();
  for (const o of orphans) {
    const key = o.reason;
    if (!byReason.has(key)) byReason.set(key, []);
    byReason.get(key).push(o);
  }
  for (const [reason, items] of byReason.entries()) {
    console.log(`  ${reason}: ${items.length}`);
  }
}